import { readFile, writeFile } from "node:fs/promises";
import ts from "typescript";
const source = await readFile(new URL("../src/data/feedbackSurvey.ts", import.meta.url), "utf8");
const compiled = ts.transpileModule(source, { compilerOptions: { module: ts.ModuleKind.ESNext, target: ts.ScriptTarget.ES2022 } }).outputText;
const schema = await import(`data:text/javascript;base64,${Buffer.from(compiled).toString("base64")}`);
export const definition = {
  version: schema.SURVEY_VERSION,
  common: schema.commonQuestions,
  complete: schema.completeQuestions,
  dropoff: schema.dropoffQuestions,
  closing: schema.closingQuestions,
};
export const fields = [...definition.common, ...definition.complete, ...definition.dropoff, ...definition.closing];
export const headers = ["접수시각(KST)", "제출 ID", "설문 버전", "사용 경로", "이메일", "이벤트 응모", "수집·이용 동의", ...fields.map((q) => q.title), "사용 화면 1", "사용 화면 2", "첨부 파일 ID"];
const generated = `// Generated by npm run sync:feedback. Do not edit.\nvar SURVEY = ${JSON.stringify(definition, null, 2)};\nvar HEADERS = ${JSON.stringify(headers, null, 2)};\n`;
const path = new URL("../server/open-beta-feedback/Schema.gs", import.meta.url);
if (process.argv.includes("--check")) {
  if (await readFile(path, "utf8") !== generated) throw new Error("Run npm run sync:feedback");
} else if (process.argv[1]?.endsWith("sync-feedback-schema.mjs")) {
  await writeFile(path, generated);
  console.log("Feedback schema synchronized.");
}
